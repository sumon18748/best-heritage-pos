import * as XLSX from 'xlsx';

export interface ExcelExportOptions {
  reportTitle: string;
  branchName: string;
  categoryFilter?: string;
  dateRange?: string;
  generatedBy: string;
  headers: string[];
  dataRows: (string | number)[][];
  summaryStats?: { label: string; value: string | number }[];
  fileName?: string;
}

export function exportReportToExcel(options: ExcelExportOptions): void {
  const {
    reportTitle,
    branchName,
    categoryFilter,
    dateRange,
    generatedBy,
    headers,
    dataRows,
    summaryStats,
    fileName,
  } = options;

  // 1. Build a structured 2D array for the Excel worksheet
  const sheetData: (string | number | null)[][] = [];

  // Branding & Header Block
  sheetData.push(['BEST HERITAGE — MULTI-BRANCH STOCK & SALES MANAGEMENT']);
  sheetData.push([reportTitle.toUpperCase()]);
  sheetData.push([
    `Branch: ${branchName} | ${categoryFilter ? `Category: ${categoryFilter} | ` : ''}Filter Period: ${dateRange || 'All Time'} | Generated By: ${generatedBy} | Date: ${new Date().toLocaleDateString('en-US')}`,
  ]);
  sheetData.push([]); // Empty row

  // Summary KPI block if present
  if (summaryStats && summaryStats.length > 0) {
    sheetData.push(['EXECUTIVE SUMMARY']);
    for (const stat of summaryStats) {
      sheetData.push([stat.label, stat.value]);
    }
    sheetData.push([]); // Empty row
  }

  // Column Headers
  sheetData.push(headers);

  // Data rows
  for (const row of dataRows) {
    sheetData.push(row);
  }

  // Optional Footer
  sheetData.push([]);
  sheetData.push([`Best Heritage Group © ${new Date().getFullYear()} — Confidential & Proprietary Report`]);

  // 2. Create worksheet
  const worksheet = XLSX.utils.aoa_to_sheet(sheetData);

  // Set column widths dynamically
  const colWidths = headers.map((header, colIdx) => {
    let maxLen = String(header).length;
    for (const row of dataRows) {
      const cellVal = row[colIdx];
      if (cellVal !== undefined && cellVal !== null) {
        maxLen = Math.max(maxLen, String(cellVal).length);
      }
    }
    return { wch: Math.min(Math.max(maxLen + 3, 12), 45) };
  });

  worksheet['!cols'] = colWidths;

  // 3. Create workbook and append sheet
  const workbook = XLSX.utils.book_new();
  const safeSheetName = reportTitle.slice(0, 31).replace(/[\\/?*[\]]/g, '');
  XLSX.utils.book_append_sheet(workbook, worksheet, safeSheetName || 'Report');

  // 4. Download as .xlsx
  const safeFileName =
    fileName ||
    `BestHeritage_${reportTitle.replace(/[^a-zA-Z0-9]/g, '_')}_${new Date().toISOString().slice(0, 10)}.xlsx`;

  XLSX.writeFile(workbook, safeFileName, { bookType: 'xlsx', type: 'binary' });
}
