import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';

export interface PdfExportOptions {
  reportTitle: string;
  branchName: string;
  dateRange?: string;
  categoryFilter?: string;
  generatedBy: string;
  headers: string[];
  dataRows: (string | number)[][];
  summaryStats?: { label: string; value: string | number }[];
  fileName?: string;
}

export function generatePdfDocument(options: PdfExportOptions): jsPDF {
  const {
    reportTitle,
    branchName,
    dateRange,
    categoryFilter,
    generatedBy,
    headers,
    dataRows,
    summaryStats,
  } = options;

  // Use landscape if more than 6 columns
  const orientation = headers.length > 6 ? 'landscape' : 'portrait';
  const doc = new jsPDF({
    orientation,
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  let currentY = 36;

  // Top header banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 54, 'F');

  // Brand Name
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(255, 255, 255);
  doc.text('BEST HERITAGE', 36, 32);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184); // slate-400
  doc.text('Smart Multi-Branch Stock, Sales & Inventory System', 170, 32);

  // Report Title
  currentY = 75;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(30, 41, 59); // slate-800
  doc.text(reportTitle.toUpperCase(), 36, currentY);

  // Metadata sub-row
  currentY += 16;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139); // slate-500

  const metaText = [
    `Branch: ${branchName}`,
    categoryFilter ? `Category: ${categoryFilter}` : null,
    `Period: ${dateRange || 'All Time'}`,
    `Generated By: ${generatedBy}`,
    `Date: ${new Date().toLocaleDateString('en-US')}`,
  ]
    .filter(Boolean)
    .join('  |  ');

  doc.text(metaText, 36, currentY);

  // Summary KPI cards if provided
  if (summaryStats && summaryStats.length > 0) {
    currentY += 14;
    const boxWidth = Math.min(130, (pageWidth - 72) / summaryStats.length - 8);
    let startX = 36;

    summaryStats.forEach((stat) => {
      doc.setFillColor(248, 250, 252); // slate-50
      doc.setDrawColor(226, 232, 240); // slate-200
      doc.roundedRect(startX, currentY, boxWidth, 38, 4, 4, 'FD');

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(7.5);
      doc.setTextColor(100, 116, 139);
      doc.text(stat.label, startX + 6, currentY + 14);

      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      doc.setTextColor(15, 23, 42);
      doc.text(String(stat.value), startX + 6, currentY + 30);

      startX += boxWidth + 8;
    });

    currentY += 46;
  } else {
    currentY += 10;
  }

  // Draw table with jspdf-autotable
  autoTable(doc, {
    startY: currentY,
    head: [headers],
    body: dataRows,
    theme: 'grid',
    styles: {
      fontSize: 8,
      cellPadding: 4,
      textColor: [30, 41, 59],
      lineColor: [226, 232, 240],
      lineWidth: 0.5,
    },
    headStyles: {
      fillColor: [16, 185, 129], // emerald-500
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8.5,
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252], // slate-50
    },
    margin: { left: 36, right: 36, bottom: 40 },
    didDrawPage: (data) => {
      // Footer on every page
      const pageNum = doc.internal.pages.length - 1;
      const totalPages = doc.getNumberOfPages();
      const pageHeight = doc.internal.pageSize.getHeight();

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(7.5);
      doc.setTextColor(148, 163, 184);
      doc.text(
        `Best Heritage Group © ${new Date().getFullYear()} — Confidential & Proprietary Report`,
        36,
        pageHeight - 18
      );
      doc.text(`Page ${pageNum} of ${totalPages}`, pageWidth - 90, pageHeight - 18);
    },
  });

  return doc;
}

export function exportReportToPdf(options: PdfExportOptions): void {
  const doc = generatePdfDocument(options);
  const safeFileName =
    options.fileName ||
    `BestHeritage_${options.reportTitle.replace(/[^a-zA-Z0-9]/g, '_')}_${new Date().toISOString().slice(0, 10)}.pdf`;

  doc.save(safeFileName);
}
